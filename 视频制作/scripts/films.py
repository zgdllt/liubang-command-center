#   headline / sub / items / asset / src / kicker / note

FILMS = {}


def film(no: int, slug: str, title: str, kicker: str, beats: list) -> None:
    epno = "总述" if slug == "overview" else f"第 {no} 集"
    FILMS[slug] = {"no": no, "slug": slug, "title": title, "kicker": kicker,
                   "epno": epno, "beats": beats}


